import { createRequire } from "node:module";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
const root = fileURLToPath(new URL(".", import.meta.url));
const require = createRequire(resolve(root, "package.json"));
const checked = spawnSync(process.execPath, [require.resolve("typescript/bin/tsc"), "--noEmit", "--strict", "--target", "ES2020", "--module", "commonjs", "src/api.ts", "src/scope.ts", "src/connection.ts", "src/sync-status.ts", "src/sync-plan.ts", "src/sync-api.ts", "src/sync-reconcile.ts", "src/sync-state.ts"], { cwd: root, stdio: "inherit" });
if (checked.status !== 0) process.exit(1);
const { build } = require("esbuild");
await build({ absWorkingDir: root, entryPoints: ["src/main.ts"], outfile: "main.js", bundle: true, platform: "browser", format: "cjs", target: "es2020", external: ["obsidian"], banner: { js: "// Generated by build.mjs; edit src/ instead." } });
